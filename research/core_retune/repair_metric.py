"""Drop invalid optional sample-Dice fields; no selection/fits change.

All selection in these studies used macro P/R/F1 and local accuracy, never
sampleF1. Correct final full-cohort sampleF1 is regenerated by the reports.
"""
from core import *


def run():
    removed=0;files=0
    def repair(v):
        nonlocal removed
        if isinstance(v,dict):
            if 'sampleF1'in v:removed+=1;v.pop('sampleF1')
            for value in v.values():repair(value)
        elif isinstance(v,list):
            for value in v:repair(value)
    for path in Path('research/core_retune/results').rglob('*.json'):
        # Protocols contain source snapshots, not metrics needing alteration.
        if path.name.endswith('protocol.json'):continue
        v=read(path);before=removed;repair(v)
        if removed>before:write(path,v);files+=1
    write('research/core_retune/results/metric-repair.json',dict(reason='Truth and predictions passed as NumPy bool made y+p a logical union, invalidating optional sampleF1. Shared metrics now converts bool/int inputs to numeric counts. No macro/micro P/R/F1 or exact-match values, selected config, objective, fits or labels change. Optional sampleF1 removed from intermediate tables; canonical full349 and product reports regenerate it correctly.',removedFields=removed,files=files,selectionUsesSampleF1=False))
    print('Removed invalid optional metric fields',removed,'from',files,'files; no fits rerun')


if __name__=='__main__':run()
