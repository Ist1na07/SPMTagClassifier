const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {regularityRestSupported}=require('../src/rest-policy.cjs');
const {compileRestEngine}=require('../research/overlay-quality/compile-rest-engine.cjs');
const profile=require('../src/models/overlay7k.json');
test('fast regular low-chord pressure is not a rest merely because31NPS is below32',()=>{
  assert.equal(regularityRestSupported(31,32,140,6600,profile.gate.ratio,profile.gate.rowRateMax),false);
  assert.equal(regularityRestSupported(22,23,140,8333,profile.gate.ratio,profile.gate.rowRateMax),false);
});
test('actual lower action rate and clearly lower context pressure remain eligible for rest',()=>{
  assert.equal(regularityRestSupported(25,26,60,4250.5,profile.gate.ratio,profile.gate.rowRateMax),true);
  assert.equal(regularityRestSupported(8,32,160,8000,profile.gate.ratio,profile.gate.rowRateMax),true);
  assert.equal(regularityRestSupported(31,32,160,10000,profile.gate.ratio,16),false);
});
